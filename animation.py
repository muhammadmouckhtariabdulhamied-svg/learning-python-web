import time

def walk():
    # Cat is standing
    print("Cat is standing")

    # Cat walks left
    print("Cat is walking left")
    time.sleep(1)

    # Cat walks right
    print("Cat is walking right")
    time.sleep(1)

    # Cat stops
    print("Cat has stopped walking")
    time.sleep(1)

    # Cat starts running
    print("Cat is starting running")
    time.sleep(1)

    # Cat runs
    print("Cat is running")
    time.sleep(1)

    # Cat stops running
    print("Cat has stopped running")
    time.sleep(1)

    # Cat jumps
    print("Cat is jumping")
    time.sleep(1)

    # Cat is landing
    print("Cat has landed")
    time.sleep(1)

if __name__ == "__main__":
    walk()

